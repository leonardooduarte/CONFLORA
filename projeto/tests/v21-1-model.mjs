import assert from 'node:assert/strict';
import {site} from './v19-fixtures.mjs';
import {reviewBotanicalV21} from '../src/core/v21Botanical.js';
import {presentV211Regions,summarizeV211Regions} from '../src/core/v21Presentation.js';
import {plants} from '../src/core/knowledge.js';
import fs from 'node:fs';
const sample=site();
const frozen=JSON.stringify(sample);
const original=reviewBotanicalV21(sample),present=presentV211Regions(original.regions);
assert.equal(original.regions.length,3);
assert.deepEqual(present.map(x=>x.displayNumber),[1,2,3]);
assert.equal(present[0].duplicateOf,null);
assert.equal(present[1].duplicateOf.displayNumber,1);
assert.equal(present[2].duplicateOf.displayNumber,1);
assert.equal(summarizeV211Regions(original.regions).unique,1);
assert.equal(JSON.stringify(sample),frozen,'V21.1 must not mutate project or plant selection');
assert.equal(original.matchCount,0,'Itapeva remains not suitable for automatic planting');
const scoped=site('IA');scoped.annotations[1].conditions={sun:'shade',moisture:'wet'};
const regionView=presentV211Regions(reviewBotanicalV21(scoped).regions);
assert(regionView[1].duplicateOf===null,'Different local conditions must keep independent evidence');
assert(regionView[2].duplicateOf.displayNumber===1,'Original shared context can use the first reference');
assert.deepEqual(regionView.map(x=>x.id),reviewBotanicalV21(scoped).regions.map(x=>x.id));
const meaningful=site();meaningful.annotations[0].notes='A caminho da casa';
assert.equal(presentV211Regions(reviewBotanicalV21(meaningful).regions)[1].duplicateOf,null);
const source=fs.readFileSync('src/features/KineticGallery.jsx','utf8');
const segment=source.split('gallerySpeciesIds=[')[1]?.split('];')[0];
assert(segment,'V21.1 gallery metadata missing');
const gallerySpeciesIds=[...segment.matchAll(/'([a-z][a-z0-9-]+)'/g)].map(m=>m[1]);
assert.equal(gallerySpeciesIds.length,9);
assert.equal(new Set(gallerySpeciesIds).size,9);
assert(gallerySpeciesIds.every(id=>plants.find(p=>p.id===id)?.image?.source),'Photo must have a verifiable credited record');
for(const name of ['conflora-courtyard.webp','conflora-observe.webp','conflora-groundcover.webp','conflora-water-roots.webp','conflora-paving.webp'])assert(fs.existsSync('public/'+name),name+' not found');
console.log('PASS V21.1: non-mutating evidence grouping, contiguous area labels, distinct area conditions, photographed and credited gallery');
