import assert from 'node:assert/strict';
import {site} from './v19-fixtures.mjs';
import {buildV20Insight} from '../src/core/v20Insight.js';
import {makeV19Scenario} from '../src/core/v19Proposal.js';
import {normalizeProject} from '../src/core/project.js';

const br=site();
const before=JSON.stringify(br);
const result=buildV20Insight(br,'pt');
assert(result,'Site insight should exist');
assert.equal(result.areaCount,3,'Original 3 evaluated areas preserved');
assert.equal(result.marks,7,'Seven annotations preserved');
assert(result.observed.some(s=>s.startsWith('3 pontos de água acumulada')));
assert(result.observed.some(s=>s.startsWith('3 saídas do telhado')));
assert(result.observed.some(s=>s.startsWith('1 superfícies pavimentadas')));
assert.equal(result.evidence,'research','Brazilian sample must remain research-only');
assert.equal(result.candidateCount,0,'No invented documented botanical match');
assert(result.evidenceLabel.includes('nenhuma planta foi validada'));
assert(result.steps.some(x=>x.id==='duration'&&x.priority==='essential'));
assert(result.steps.some(x=>x.id==='building'&&x.priority==='essential'));
assert(result.steps.some(x=>x.id==='soil'&&x.priority==='essential'));
assert(result.interpretations.some(x=>x.includes('drenagem aparentemente lenta')||x.includes('drenagem aparentemente lenta'.replace('drenagem','drenagem'))));
assert.equal(JSON.stringify(br),before,'Model must not change project observations or user data');
for(const task of result.steps){assert(task.label&&task.why&&task.how&&task.follow,'Action should explain what, why and how');}
const english=buildV20Insight(br,'en');
assert(english.evidenceLabel.includes('no planting'));
assert(english.steps.some(x=>x.label.includes('Record pooling')));
assert(english.observed.some(x=>x.includes('roof outlets')));
const area=site();area.context.sun='full';area.annotations[0].conditions={sun:'unknown',soil:'medium'};
const origin=buildV20Insight(area).regions[0].origin;
assert.equal(origin.find(x=>x.key==='sun').origin,'area','Explicitly unknown override must remain area-specific');
assert.equal(origin.find(x=>x.key==='sun').value,'unknown');
assert.equal(origin.find(x=>x.key==='soil').origin,'area');
assert.equal(origin.find(x=>x.key==='moisture').origin,'site');
const risk=site();risk.context.duration='persistent';risk.context.building='near';
assert(buildV20Insight(risk).risk);
const ia=site('IA');const iaResult=buildV20Insight(ia,'en');assert(iaResult.candidateCount>0);
assert(makeV19Scenario(br,'A','exploratory').created);
assert(makeV19Scenario(br,'B','exploratory').created);
const compared=buildV20Insight(br);
assert.equal(compared.scenarios.length,2);
assert(compared.scenarios.every(x=>x.count>0&&x.mode==='exploratory'));
const saved=normalizeProject(JSON.parse(JSON.stringify(br)));
assert.equal(buildV20Insight(saved).marks,7);
assert.equal(buildV20Insight(saved).scenarios[1].count,compared.scenarios[1].count);
const empty=site();empty.annotations=[];empty.context={...empty.context,soil:'unknown',duration:'unknown',building:'unknown',sun:'unknown',moisture:'unknown'};
const unclear=buildV20Insight(empty);
assert(unclear.steps.length>0&&unclear.candidateCount===0);
console.log('PASS V20 insight: Itapeva 7 observations, no fabricated planting, 3 areas, area/site inheritance, next checks, A/B, Iowa, English, imported projects');
